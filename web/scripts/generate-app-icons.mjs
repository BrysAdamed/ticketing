const out = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'app',
  'shared',
  'ui',
  'icon',
  'app-icons.generated.ts',
);

const entries = [...APP_ICON_NAMES].sort().map((name) => {
  const svg = tabler[name];
  if (typeof svg !== 'string') throw new Error(`${name}: not a Tabler icon`);
  if (svg.includes("'") || svg.includes('\\')) throw new Error(`${name}: unexpected quote or backslash`);
  return `  ${name}: '${svg}',`;
});

const code = [
  '// Generated by scripts/generate-app-icons.mjs from @ng-icons/tabler-icons (Tabler Icons, MIT). Do not edit.',
  '',
  '/// Icons registered app-wide (root injector). Feature-specific icons belong in the feature',
  "/// component's `viewProviders: [provideIcons({ ... })]` so they are bundled with the feature.",
  'export const APP_ICONS: Readonly<Record<string, string>> = {',
  ...entries,
  '};',
  '',
].join('\n');
writeFileSync(out, await format(code, { ...(await resolveConfig(out)), filepath: out }));
console.log(`${entries.length} icons written to ${out}`);
