// Generates src/app/shared/avatars/avatar-art.generated.ts (D-130): every vendor/fluent-emoji/flat/<key>.svg
// (Microsoft Fluent Emoji, Flat, MIT) optimised with SVGO into one map from avatar icon key to SVG markup.
// Run `npm run generate:avatars` after adding or replacing an SVG there.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { optimize } from 'svgo';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(web, 'vendor', 'fluent-emoji', 'flat');
const out = join(web, 'src', 'app', 'shared', 'avatars', 'avatar-art.generated.ts');

const entries = readdirSync(source)
  .filter((file) => file.endsWith('.svg'))
  .sort()
  .map((file) => {
    const svg = optimize(readFileSync(join(source, file), 'utf8'), {
      multipass: true,
      plugins: ['preset-default', 'removeDimensions'],
    }).data;
    if (svg.includes("'")) throw new Error(`${file}: unexpected single quote`);
    return `  ${basename(file, '.svg')}: '${svg}',`;
  });

const code = [
  '// Generated by scripts/generate-avatar-art.mjs from vendor/fluent-emoji (Microsoft Fluent Emoji, MIT). Do not edit.',
  'export const AVATAR_ART: Readonly<Record<string, string>> = {',
  ...entries,
  '};',
  '',
].join('\n');
writeFileSync(out, await format(code, { ...(await resolveConfig(out)), filepath: out }));
console.log(`${entries.length} avatars written to ${out}`);
